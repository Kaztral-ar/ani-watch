#!/bin/sh
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
OUT="$ROOT/dist/aniwatch"
mkdir -p "$ROOT/dist"
{
    printf '%s\n' '#!/bin/sh' '# Generated by scripts/build.sh; edit lib/aniwatch/*.sh instead.'
    for module in core config http provider_jikan provider_hianime ui player cli main; do
        printf '\n# ---- %s ----\n' "$module"
        sed '1{/^#!\/bin\/sh$/d;}' "$ROOT/lib/aniwatch/$module.sh"
    done
    printf '\naniwatch_main "$@"\n'
} > "$OUT"
chmod 755 "$OUT"
printf 'Built %s\n' "$OUT"
