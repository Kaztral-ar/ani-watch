aw_header() {
    printf '\n\033[1;36m  _          _ __        __      _       _\033[0m\n'
    printf '\033[1;36m /_\\  _ __ (_)\\ \\      / /__ _| |_ ___| |__\033[0m\n'
    printf '\033[1;36m//_\\\\| \'_ \\| |\\ \\ /\\ / / _ ` | __/ __| \'_ \\\033[0m\n'
    printf '\033[1;36m/  _  \\ | | | | \\ V  V / (_| | || (__| | | |\033[0m\n'
    printf '\033[1;36m\\_/ \\_/_| |_|_|  \\_/\\_/ \\__,_|\\__\\___|_| |_|\033[0m\n\n'
}

aw_show_results() {
    aw_data=$1
    printf '%s\n' "$aw_data" | aw_print_results | awk -F '\t' 'BEGIN { printf "%-8s %-48s %-16s %-12s %s\n", "ID", "TITLE", "SCORE", "EPISODES", "TYPE"; print "-----------------------------------------------------------------------------------------------" } { printf "%-8s %-48.48s %-16s %-12s %s\n", $1, $2, $3, $4, $5 }'
}
